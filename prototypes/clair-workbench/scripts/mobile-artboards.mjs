// Regenerates src/mobile-artboards.ts from the Clair UI design canvas.
//
// The mobile screens have a Live/Design toggle (`?review=1`) that shows the
// artboard next to the running implementation. Transcribing the artboards by
// hand is exactly the drift this comparison exists to catch, so the snapshots
// are copied mechanically instead:
//
//   python3 .claude/skills/clair-workbench-sync/scripts/canvas_edit.py \
//     extract <saved-canvas.html> /tmp/canvas/
//   node scripts/mobile-artboards.mjs /tmp/canvas
//
// Each artboard's <helmet> CSS is scoped under `.dc-board` so the artboard's
// own `.cl` / `.card` / `.sw` rules cannot leak into the live mock around it.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const BOARDS = {
  概要: 'MobileHome.dc.html',
  セッション: 'MobileOverview.dc.html',
  アクティビティ: 'MobileActivity.dc.html',
  設定: 'MobileSettings.dc.html',
  terminal: 'MobileTerminal.dc.html',
  pairing: 'MobilePairing.dc.html',
};

const dir = process.argv[2];
if (!dir) throw new Error('usage: node scripts/mobile-artboards.mjs <extracted-canvas-dir>');

const between = (s, open, close) => {
  const a = s.indexOf(open);
  const b = s.indexOf(close, a);
  if (a < 0 || b < 0) throw new Error(`missing ${open}`);
  return s.slice(a + open.length, b);
};

/** Prefix every selector with `.dc-board`, and drop the page-level rules
 *  (`body`, `a`) that only make sense when the artboard is the whole page. */
const scope = (css) =>
  css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('}')
    .map((chunk) => {
      const i = chunk.indexOf('{');
      if (i < 0) return '';
      const selectors = chunk.slice(0, i).trim();
      const body = chunk.slice(i + 1).trim();
      if (!selectors || !body) return '';
      const kept = selectors
        .split(',')
        .map((s) => s.trim())
        .filter((s) => s && !/^(body|a)\b/.test(s))
        .map((s) => `.dc-board ${s}`);
      return kept.length ? `${kept.join(', ')} { ${body} }` : '';
    })
    .filter(Boolean)
    .join('\n');

const entries = Object.entries(BOARDS).map(([key, file]) => {
  const src = readFileSync(join(dir, file), 'utf8');
  const css = scope(between(src, '<style>', '</style>'));
  const html = between(src, '</helmet>', '</x-dc>').trim();
  return [key, file, css, html];
});

const lit = (s) => JSON.stringify(s);

const out = `// GENERATED by scripts/mobile-artboards.mjs — do not edit by hand.
//
// Verbatim copies of the mobile artboards on the Clair UI design canvas, used
// by the \`?review=1\` Live/Design toggle to put the running screen and the
// artboard side by side. Regenerate after the canvas changes; never hand-patch
// a snapshot, or the comparison starts agreeing with the mock instead of the
// canvas.

export type ArtboardKey = ${entries.map(([k]) => lit(k)).join(' | ')};

export const artboards: Record<ArtboardKey, { file: string; css: string; html: string }> = {
${entries
  .map(
    ([key, file, css, html]) =>
      `  ${lit(key)}: {\n    file: ${lit(file)},\n    css: ${lit(css)},\n    html: ${lit(html)},\n  },`,
  )
  .join('\n')}
};
`;

writeFileSync('src/mobile-artboards.ts', out);
console.log(`wrote src/mobile-artboards.ts (${out.length} bytes, ${entries.length} artboards)`);
